// ============================================================================
//  hud_group.h —— P3-07 第一批用例（硬件监控悬浮窗 monitor.hardware_hud）
//
//  这一组测两件事，缺一不可：
//    ① **显示模型**（plugins/common/HudMetrics，与插件**编同一份源码**）：
//       逐项开关、格式化边界、以及本功能最硬的那条纪律 ——
//       "**读不到的指标必须如实写出原因，绝不允许显示 0 或留空**"；
//    ② **真实悬浮窗**（build/bin/plugins 下真正装上的那个 DLL）：
//       启用即出一个置顶 / 分层 / 不抢焦点 / 点击穿透的小面板，
//       面板上的读数来自**本机真实硬件**（内存与磁盘温度可与平台层读回值对账），
//       CPU 温度**如实报"需要 PawnIOLib.dll"**（第二里程碑才会变成真实读数），
//       逐项开关会**当场改变面板行数**（窗口高度跟着变），
//       位置持久化、复位、可拖拽切换、停用后不留置顶窗口。
//
//  ⚠ 与悬浮层组（overlay_group）的区别：那一组验的是"像素有没有真的变亮/变暗"，
//     本组验的是"**面板上写的是不是真话**"——所以断言落在
//     "不可用项不得是数字"与"可用项的读数必须与平台层读数同源"上。
// ============================================================================

