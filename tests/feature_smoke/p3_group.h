// ============================================================================
//  p3_group.h —— P3 高风险波次用例
//      P3-01 虚拟桌面增强（window.virtual_desktop）
//      P3-02 文件锁定解除（file.unlock）
//      P3-14 USB 设备管控（security.usb_control）
//
//  这一组的特殊性：**被测对象会动到用户环境里"有代价"的东西**。
//  所以自检的纪律比别处更硬：
//      * P3-01：搬的是**自检自己的窗口**（探针子进程窗口 / 探针面板），
//        而且每一次搬都**读数回验**、**搬回原位**；切换桌面那一步**不真按**
//        （那会把用户的屏幕切走），只验机制与"按键被拒绝时如实报错"；
//      * P3-02：**锁的是自检自己造的临时文件**（不碰用户的任何文件），
//        占用源是一个**自检自己起的子进程**（真能被结束，结束了也不心疼）；
//        删除走回收站，且验的是"没解除占用时必须失败"；
//      * P3-14：**绝不执行设备弹出**（用户的移动硬盘可能正在备份，一次
//        "测试性弹出"是灾难），能验的是判据、界面一致性与二次确认拦不拦得住。
// ============================================================================

