//  power_group.h —— 系统与媒体组用例
//      P2-06 快速关机 / 重启 / 休眠（monitor.power_panel）
//      P2-07 定时任务（monitor.scheduler）
//
//  这两项的共同点：**后果不可撤销**（关机、改麦克风、打断当前工作），
//  所以这一组的断言重心不是"功能能不能用"，而是：
//      * **撤销通道真的有效**：倒计时中点「取消」→ 电源请求一次都没发出去；
//      * **到点真的执行**：倒计时归零 → 请求带着正确的 action/timeout 交到提权助手；
//      * **助手不可用时如实报错**（fail-closed），绝不假装成功；
//      * **休眠恢复不丢任务**：错过的任务会被补触发并如实标注。
//
//  ⚠ 这一组**绝不能在自检里真的关机 / 锁屏**：
//      电源请求打到"记录型提权桩"（`RecordingElevationService`）就停住 ——
//      整条链路（确认 → 倒计时 → 参数组装 → 请求）都真实跑，只在最后一步之前截住。
//      「锁定」按钮连点都不点（点了会真的锁屏），只断言"它不需要提权"这条决策。
//
//  ⚠ 会改动真实系统的地方只有一处：P2-07 的"定时静音"任务会**真的改麦克风静音**，
//     用例开头用 `MicMuteGuard` 记下用户原来的状态，结束时写回并回读确认。
// ============================================================================

